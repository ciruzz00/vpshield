const (
	MainConfig = "/etc/ssh/sshd_config"
	DropInDir  = "/etc/ssh/sshd_config.d"
	DropIn     = "/etc/ssh/sshd_config.d/00-vpshield.conf" // 00- so it wins: first value set is kept by sshd
)

type Settings struct {
	Port                int
	PermitRootLogin     string // no | prohibit-password | yes
	PasswordAuth        bool
	MaxAuthTries        int
	LoginGraceTime      int // seconds
	ClientAliveInterval int
	ClientAliveCountMax int
	X11Forwarding       bool
	AllowTcpForwarding  bool
	AllowAgentForward   bool
	AllowUsers          []string
}

// managed lists the directives we own (lower case, as printed by sshd -T).
var managed = []string{
	"port", "permitrootlogin", "passwordauthentication", "kbdinteractiveauthentication",
	"challengeresponseauthentication", "pubkeyauthentication", "permitemptypasswords",
	"maxauthtries", "logingracetime", "clientaliveinterval", "clientalivecountmax",
	"x11forwarding", "allowtcpforwarding", "allowagentforwarding", "allowusers",
}

// Effective returns `sshd -T` as a map (needs root). Empty map on failure.
func Effective(h *system.Host) map[string]string {
	m := map[string]string{}
	out, err := h.Query("sshd", "-T")
	if err != nil {
		return m
	}
	for _, line := range strings.Split(out, "\n") {
		k, v, ok := strings.Cut(strings.TrimSpace(line), " ")
		if !ok {
			continue
		}
		k = strings.ToLower(k)
		if _, dup := m[k]; dup && k == "port" {
			m[k] += " " + v // multiple Port lines
			continue
		}
		m[k] = v
	}
	return m
}

// Current reads the effective settings, with OpenSSH defaults as fallback.
func Current(h *system.Host) Settings {
	e := Effective(h)
	atoi := func(k string, def int) int {
		if n, err := strconv.Atoi(strings.Fields(e[k] + " x")[0]); err == nil {
			return n
		}
		return def
	}
	yes := func(k string, def bool) bool {
		v, ok := e[k]
		if !ok {
			return def
		}
		return v == "yes" || v == "all" || v == "local"
	}
	s := Settings{
		Port:                atoi("port", 22),
		PermitRootLogin:     e["permitrootlogin"],
		PasswordAuth:        yes("passwordauthentication", true),
		MaxAuthTries:        atoi("maxauthtries", 6),
		LoginGraceTime:      atoi("logingracetime", 120),
		ClientAliveInterval: atoi("clientaliveinterval", 0),
		ClientAliveCountMax: atoi("clientalivecountmax", 3),
		X11Forwarding:       yes("x11forwarding", false),
		AllowTcpForwarding:  yes("allowtcpforwarding", true),
		AllowAgentForward:   yes("allowagentforwarding", true),
	}
	if s.PermitRootLogin == "without-password" {
		s.PermitRootLogin = "prohibit-password"
	}
	if s.PermitRootLogin == "" {
		s.PermitRootLogin = "prohibit-password"
	}
	if v := e["allowusers"]; v != "" {
		s.AllowUsers = strings.Fields(v)
	}
	return s
}

// Hardened returns recommended settings starting from cur.
func Hardened(cur Settings) Settings {
	s := cur
	s.PermitRootLogin = "prohibit-password"
	s.PasswordAuth = false
	s.MaxAuthTries = 3
	s.LoginGraceTime = 30
	s.ClientAliveInterval = 300
	s.ClientAliveCountMax = 2
	s.X11Forwarding = false
	// VS Code Remote-SSH and tunnels need TCP forwarding: keep the user's choice
	return s
}

func yn(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

// RenderDropIn builds the 00-vpshield.conf drop-in.
func RenderDropIn(s Settings) string {
	var b strings.Builder
	b.WriteString("# Managed by vpshield - regenerated by the SSH wizard.\n")
	b.WriteString("# Loaded first, so these values win over later files.\n")
	fmt.Fprintf(&b, "Port %d\n", s.Port)
	fmt.Fprintf(&b, "PermitRootLogin %s\n", s.PermitRootLogin)
	fmt.Fprintf(&b, "PasswordAuthentication %s\n", yn(s.PasswordAuth))
	fmt.Fprintf(&b, "KbdInteractiveAuthentication %s\n", yn(s.PasswordAuth))
	b.WriteString("PubkeyAuthentication yes\n")
	b.WriteString("PermitEmptyPasswords no\n")
	fmt.Fprintf(&b, "MaxAuthTries %d\n", s.MaxAuthTries)
	fmt.Fprintf(&b, "LoginGraceTime %d\n", s.LoginGraceTime)
	fmt.Fprintf(&b, "ClientAliveInterval %d\n", s.ClientAliveInterval)
	fmt.Fprintf(&b, "ClientAliveCountMax %d\n", s.ClientAliveCountMax)
	fmt.Fprintf(&b, "X11Forwarding %s\n", yn(s.X11Forwarding))
	fmt.Fprintf(&b, "AllowTcpForwarding %s\n", yn(s.AllowTcpForwarding))
	fmt.Fprintf(&b, "AllowAgentForwarding %s\n", yn(s.AllowAgentForward))
	if len(s.AllowUsers) > 0 {
		fmt.Fprintf(&b, "AllowUsers %s\n", strings.Join(s.AllowUsers, " "))
	}
	return b.String()
}

var includeRe = regexp.MustCompile(`(?i)^\s*Include\s+/etc/ssh/sshd_config\.d/\*\.conf`)

// PatchMain makes sure the drop-in directory is included at the top of
// sshd_config and comments out our directives in the global section so the
// drop-in is the single source of truth. Match blocks are left untouched.
func PatchMain(main string) (string, bool) {
	lines := strings.Split(main, "\n")
	changed := false
	hasInclude := false
	inMatch := false
	for i, l := range lines {
		t := strings.TrimSpace(l)
		if includeRe.MatchString(l) {
			hasInclude = true
			continue
		}
		if t == "" || strings.HasPrefix(t, "#") {
			continue
		}
		key := strings.ToLower(strings.Fields(t)[0])
		if key == "match" {
			inMatch = true
		}
		if inMatch {
			continue
		}
		for _, m := range managed {
			if key == m {
				lines[i] = "# vpshield: " + l
				changed = true
			}
		}
	}
	out := strings.Join(lines, "\n")
	if !hasInclude {
		out = "# Added by vpshield\nInclude /etc/ssh/sshd_config.d/*.conf\n\n" + out
		changed = true
	}
	return out, changed
}

// KeyHolders lists accounts that have a non-empty authorized_keys.
func KeyHolders() []string {
	var users []string
	check := func(user, home string) {
		for _, f := range []string{"authorized_keys", "authorized_keys2"} {
			if st, err := os.Stat(filepath.Join(home, ".ssh", f)); err == nil && st.Size() > 0 {
				users = append(users, user)
				return
			}
		}
	}
	check("root", "/root")
	homes, _ := filepath.Glob("/home/*")
	for _, h := range homes {
		check(filepath.Base(h), h)
	}
	return users
}

func selinuxEnforcing(h *system.Host) bool {
	if !h.Has("getenforce") {
		return false
	}
	out, _ := h.Query("getenforce")
	return strings.TrimSpace(out) != "Disabled"
}

func socketActivated(h *system.Host) bool {
	if h.Distro.Init != system.InitSystemd {
		return false
	}
	out, _ := h.Query("systemctl", "is-active", "ssh.socket")
	return strings.TrimSpace(out) == "active"
}

// restartStep restarts sshd the right way for the host and registers the
// same command as rollback hook.
func restartStep(h *system.Host) plan.Step {
	svc := h.Distro.Service("sshd")
	if socketActivated(h) {
		return plan.Func("restart ssh (socket activated)", "$ systemctl daemon-reload && systemctl restart ssh.socket ssh.service", func(h *system.Host) (string, error) {
			h.AddRestoreHook("systemctl", "daemon-reload")
			h.AddRestoreHook("systemctl", "restart", "ssh.socket", "ssh.service")
			if _, err := h.Run("systemctl", "daemon-reload"); err != nil {
				return "", err
			}
			return h.Run("systemctl", "restart", "ssh.socket", "ssh.service")
		})
	}
	return plan.Func("restart "+svc, "existing sessions stay connected", func(h *system.Host) (string, error) {
		if h.Distro.Init == system.InitOpenRC {
			h.AddRestoreHook("rc-service", svc, "restart")
		} else {
			h.AddRestoreHook("systemctl", "restart", svc)
		}
		return h.ServiceRestart(svc)
	})
}

// Options steer BuildPlan.
type Options struct {
	LimitNewPort   bool // rate limit the new SSH port in the firewall
	DeadmanSeconds int
}

// BuildPlan creates the plan to go from cur to want.
func BuildPlan(h *system.Host, fw firewall.Backend, cur, want Settings, o Options) *plan.Plan {
	p := &plan.Plan{Title: "Apply SSH configuration", Deadman: o.DeadmanSeconds}
	p.Backups = []string{MainConfig, DropIn}

	// --- lockout guards
	holders := KeyHolders()
	if !want.PasswordAuth {
		if len(holders) == 0 {
			p.Warn("NO authorized_keys found on this server and password login will be DISABLED: you WILL be locked out. Add a key first (ssh-copy-id).")
		} else {
			p.Warn("password login disabled: key holders found: %s", strings.Join(holders, ", "))
		}
	}
	if want.PermitRootLogin == "no" {
		nonRoot := 0
		for _, u := range holders {
			if u != "root" {
				nonRoot++
			}
		}
		if nonRoot == 0 && !want.PasswordAuth {
			p.Warn("root login disabled but only root has an SSH key: create a sudo user with a key first")
		}
	}
	if len(want.AllowUsers) > 0 {
		me := system.LoginUser()
		found := false
		for _, u := range want.AllowUsers {
			if u == me || strings.HasPrefix(u, me+"@") {
				found = true
			}
		}
		if !found {
			p.Warn("AllowUsers does not contain your user %q", me)
		}
	}

	// --- port change prerequisites
	if want.Port != cur.Port {
		port := strconv.Itoa(want.Port)
		if h.Distro.Family == system.FamilyRHEL && selinuxEnforcing(h) {
			if !h.Has("semanage") {
				p.Add(plan.Install(h, "semanage"))
			}
			p.Add(plan.Func("SELinux: label tcp/"+port+" as ssh_port_t", "$ semanage port -a -t ssh_port_t -p tcp "+port, func(h *system.Host) (string, error) {
				out, err := h.Run("semanage", "port", "-a", "-t", "ssh_port_t", "-p", "tcp", port)
				if err != nil && strings.Contains(out, "already defined") {
					return h.Run("semanage", "port", "-m", "-t", "ssh_port_t", "-p", "tcp", port)
				}
				return out, err
			}))
		}
		if fw.Active() {
			p.Add(firewall.Wrap(fw, fw.AllowSteps(system.PortRule{Port: want.Port, Proto: "tcp", Limit: o.LimitNewPort, Comment: "ssh"}))...)
			p.Warn("old port %d stays open until you confirm the new one works", cur.Port)
		} else {
			p.Warn("firewall is not active: port %d will be reachable as soon as sshd restarts", want.Port)
		}
	}

	// --- config files
	main := system.ReadFile(MainConfig)
	if patched, changed := PatchMain(main); changed && main != "" {
		p.Add(plan.File(MainConfig, patched, 0o600))
	}
	p.Add(
		plan.Func("create "+DropInDir, "", func(h *system.Host) (string, error) {
			if h.DryRun {
				return "[dry-run] mkdir " + DropInDir, nil
			}
			return "", os.MkdirAll(DropInDir, 0o755)
		}),
		plan.File(DropIn, RenderDropIn(want), 0o600),
		plan.Func("validate config (sshd -t)", "$ sshd -t", func(h *system.Host) (string, error) {
			out, err := h.Run("sshd", "-t")
			if err != nil {
				return out, fmt.Errorf("sshd rejected the config, plan aborted: %w", err)
			}
			if h.DryRun {
				return out, nil
			}
			eff := Effective(h)
			if got := strings.Fields(eff["port"] + " ")[0]; got != strconv.Itoa(want.Port) && got != "" {
				return out, fmt.Errorf("effective port is %s, expected %d (another config file overrides it)", got, want.Port)
			}
			return "config OK", nil
		}),
		restartStep(h),
		plan.Func(fmt.Sprintf("verify sshd listens on %d", want.Port), "", func(h *system.Host) (string, error) {
			if h.DryRun {
				return "[dry-run] skipped", nil
			}
			for i := 0; i < 20; i++ {
				if h.IsListening(want.Port) {
					return "listening", nil
				}
				time.Sleep(500 * time.Millisecond)
			}
			return "", fmt.Errorf("nothing listens on %d after restart", want.Port)
		}),
	)
	return p
}

// FinalizePortPlan runs after the user confirmed the new port works:
// close the old port, update fail2ban, remember the port.
func FinalizePortPlan(h *system.Host, fw firewall.Backend, st *system.State, oldPort, newPort int, closeOld bool) *plan.Plan {
	p := &plan.Plan{Title: fmt.Sprintf("Finalize SSH port %d", newPort)}
	if closeOld && oldPort != newPort && fw.Active() {
		p.Add(firewall.Wrap(fw, fw.RemoveSteps(oldPort, "tcp"))...)
	}
	p.Add(plan.Func("update fail2ban sshd jail port", "", func(h *system.Host) (string, error) {
		return fail2ban.SetSSHPort(h, newPort)
	}))
	p.AfterApply = func(h *system.Host) error {
		st.SSHPort = newPort
		return h.SaveState(st)
	}
	return p
}

// ValidUser checks an AllowUsers token.
var userRe = regexp.MustCompile(`^[a-z_][a-z0-9_.-]*[$]?(@[0-9a-fA-F.:/*?]+)?$`)

func ParseUsers(s string) ([]string, error) {
	var out []string
	for _, u := range strings.FieldsFunc(s, func(r rune) bool { return r == ',' || r == ' ' }) {
		if !userRe.MatchString(u) {
			return nil, fmt.Errorf("invalid user %q", u)
		}
		out = append(out, u)
	}
	return out, nil
}
